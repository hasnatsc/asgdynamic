SELECT r.name, '', TRUE, 'seed', NOW()
FROM (VALUES
    ('ROLE_ACCOUNTS'), ('ROLE_ADMIN'), ('ROLE_ADMINISTRATOR'), ('ROLE_APPROVAL'),
    ('ROLE_BANK_SETUP'), ('ROLE_BOOKING_REPORT'), ('ROLE_BOOKING_REVISION'),
    ('ROLE_CI_APPROVAL'), ('ROLE_CI_CHECKER'), ('ROLE_CI_ISSUE_VIEW'), ('ROLE_CI_MAKER'),
    ('ROLE_COMMERCIAL'), ('ROLE_COMMERCIAL_CI_ISSUE'), ('ROLE_COMMERCIAL_CI_REPORT'),
    ('ROLE_COMMERCIAL_CI_REVISION'), ('ROLE_COMMERCIAL_DOCUMENT_NAMES'),
    ('ROLE_COMMERCIAL_LC_COST_HEAD'), ('ROLE_COMMERCIAL_LC_RECEIVING'),
    ('ROLE_COMMERCIAL_LC_REPORT'), ('ROLE_COMMERCIAL_LC_REVISION'),
    ('ROLE_COMMERCIAL_LC_TERMS_&_CONDITIONS'), ('ROLE_COMMERCIAL_PI_ISSUE'),
    ('ROLE_COMMERCIAL_PI_REPORT'), ('ROLE_COMMERCIAL_PI_REVISION'),
    ('ROLE_COMMERCIAL_PI_TERMS_&_CONDITIONS'), ('ROLE_COMMERCIAL_SETUP'),
    ('ROLE_DELIVERY_ORDER'), ('ROLE_DELIVERY_ORDER_REPORT_LIST'),
    ('ROLE_DELIVERY_ORDER_REQUEST'), ('ROLE_EMPLOYEE'), ('ROLE_FABRICS_DELIVERY'),
    ('ROLE_FABRICS_DELIVERY_REPORT_LIST'), ('ROLE_FINISHED_GOODS_TRANSACTION'),
    ('ROLE_GREIGE_FABRICS_TRANSACTION'), ('ROLE_HRM'), ('ROLE_IMPORT_MAKER'),
