-- Seeds the 71 role names from the ASFL admin export as empty-shell sec_fabric_roles rows —
-- name only, zero sec_fabric_role_screen_grants. They do nothing on their own: asgdynamic's
-- Screen enum only covers the 10 fabric-document screens (BOOKING, BPO, RPI, WWO, PWO, GR, DO,
-- FD, FABRIC_SETUP, SECURITY_ADMIN), so most of these names (ROLE_MARKETING_MANAGER,
-- ROLE_COMMERCIAL_LC_REVISION, etc.) have no real screen to grant yet. This just pre-creates
-- the catalog so an admin can assign real Screen x Verb grants via /setup/roles later, without
-- guessing what each name should actually permit.
--
-- APPLY THIS BY HAND — same caveat as V7-V10.
--
-- Idempotent — safe to re-run.

