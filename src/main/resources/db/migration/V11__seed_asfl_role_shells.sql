    ('ROLE_MARKETING_ADMIN'), ('ROLE_MARKETING_EXECUTIVE'), ('ROLE_MARKETING_MANAGER'),
    ('ROLE_MARKETING_TEAMLEAD'), ('ROLE_OPEN_API'), ('ROLE_PI_APPROVAL'),
    ('ROLE_PI_CHECKER'), ('ROLE_PI_MAKER'), ('ROLE_PLANNING'), ('ROLE_PLANNING_HEAD'),
