    ('ROLE_ROLE_ADMIN_IMPORT_COMMERCIAL'), ('ROLE_SALES'),
    ('ROLE_SALES_&_MARKETING_SETUP'), ('ROLE_SERVICE'), ('ROLE_SETUP'),
    ('ROLE_SOLID_DYED_BOOKING'), ('ROLE_SUPER_ADMIN'), ('ROLE_WEAVING_STORE'),
    ('ROLE_YARN_DYED_BOOKING')
) AS r(name)
WHERE NOT EXISTS (SELECT 1 FROM sec_fabric_roles sr WHERE sr.name = r.name);
