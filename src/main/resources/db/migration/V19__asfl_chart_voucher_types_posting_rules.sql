FROM acc_posting_rules p
JOIN tmp_asfl_rules r ON p.code = 'ASFL-' || r.event_type
CROSS JOIN (VALUES (1, 'DEBIT'), (2, 'CREDIT')) AS leg (sequence, side)
WHERE NOT EXISTS (SELECT 1 FROM acc_posting_rule_lines l WHERE l.rule_id = p.id);
