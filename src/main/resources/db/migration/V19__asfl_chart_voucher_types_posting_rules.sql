INSERT INTO acc_posting_rules (organization_id, code, name, event_type, effective_from, description,
                               active, deleted, version, created_by, created_at)
SELECT o.id, 'ASFL-' || r.event_type, r.name, r.event_type, DATE '2000-01-01', 'ASFL chart rule (V19)',
       TRUE, FALSE, 0, 'V19', now()
FROM org_organizations o
CROSS JOIN tmp_asfl_rules r
WHERE NOT EXISTS (SELECT 1 FROM acc_posting_rules x
                  WHERE x.organization_id = o.id AND x.event_type = r.event_type
                    AND x.effective_to IS NULL AND x.active AND NOT x.deleted)
  AND EXISTS (SELECT 1 FROM acc_accounts a WHERE a.organization_id = o.id AND a.code = r.debit_code AND a.usage_type <> 'SUMMARY')
  AND EXISTS (SELECT 1 FROM acc_accounts a WHERE a.organization_id = o.id AND a.code = r.credit_code AND a.usage_type <> 'SUMMARY')
ON CONFLICT (organization_id, code) DO NOTHING;

