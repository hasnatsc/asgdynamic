-- =============================================================================================
-- V19 - The ASFL chart of accounts, voucher types, and a posting rule for every accounts event.
--
-- 1. Voucher types. Every ledger entry is numbered in the series of its kind - JV, PV, RV, CV, SV,
--    PUV, PDV (Document numbering > Accounts) - and the type is stored on the entry.
--
-- 2. The ASFL chart of accounts (406 accounts from the legacy system, 8-digit codes) for every
--    organization, as a tree. Corrections to the legacy nesting, where it contradicted the codes:
--      * 12020201/12020202 LC Receivable (listed under Property, Plant & Equipment) -> under
--        12020200 Bills Receivables;
--      * 20200000 Current Liabilities (listed inside Non-Current) -> under 20000000;
--      * 51000200 Materials Consumed and 55000000 Financial Expenses (listed inside income
--        "Others") -> under 51000000 and 50000000; 55010100/55010200 -> under 55000000;
--      * 53011100 ... 53011800 are group heads (Advertisement, Utility Expenses, ...) with their own
--        sub-accounts, not leaves of 53011000 Obsolete Stock.
--    Two accounts added because postings need them:
--      * 30100101 Share Capital - Paid Up (30100100 had no account for paid-up capital);
--      * 12010112 Greige Fabric (greige stock between weaving and dyeing).
--    Receivables (12020101-05, 12020108, 12020201-02) and payables (20200101, 20200106) are
--    CONTROL accounts: every line names the customer or supplier, and no manual journals.
--
-- 3. A posting rule for every rule-driven event, on these accounts, effective from 2000-01-01.
--    Events that already have a live rule in an organization keep it.
--
-- Idempotent: accounts and rules that exist are left alone.
-- =============================================================================================

-- ---------------------------------------------------------------------------------------------
-- 1. Voucher types
-- ---------------------------------------------------------------------------------------------
