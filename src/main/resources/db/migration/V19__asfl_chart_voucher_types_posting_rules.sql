UPDATE acc_accounts a
SET parent_id = p.id
FROM tmp_asfl_chart c
JOIN acc_accounts p ON p.code = c.parent_code
WHERE a.code = c.code
  AND p.organization_id = a.organization_id
  AND a.parent_id IS NULL
  AND c.parent_code IS NOT NULL;

